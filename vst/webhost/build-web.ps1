# ============================================================================
#  Builds web/index.html (and its GitHub Pages copy docs/index.html): ONE
#  self-contained file from the plugin UI (vst/ui), the factory presets and
#  the web host + JS engine (this folder).
#  Usage: powershell -ExecutionPolicy Bypass -File vst\webhost\build-web.ps1
# ============================================================================
$ErrorActionPreference = 'Stop'
$vst  = Split-Path $PSScriptRoot -Parent
$repo = Split-Path $vst -Parent
$ui   = Join-Path $vst 'ui'
$utf8 = [Text.UTF8Encoding]::new($false)
$read = { param($path) [IO.File]::ReadAllText($path, $utf8) }

$html = & $read (Join-Path $ui 'index.html')
$version = (Select-String -Path (Join-Path $vst 'CMakeLists.txt') -Pattern 'project\(NoStringsVST VERSION ([0-9.]+)').Matches[0].Groups[1].Value

function Script([string]$code) {
    if ($code -match '</script') { throw 'inlined code must not contain </script' }
    return "<script>`n$code`n</script>"
}

# CSS
$css = & $read (Join-Path $ui 'css\style.css')
$html = $html.Replace('<link rel="stylesheet" href="css/style.css">', "<style>`n$css`n</style>")

# Web host + DSP + factory presets go in before the bridge (engine-juce.js) is constructed
$hostScripts = @(
    (Script ("// the 64 factory presets (vst/presets/factory_presets.json)`nconst FACTORY_JSON = " + (& $read (Join-Path $vst 'presets\factory_presets.json')).Trim() + ';')),
    (Script (& $read (Join-Path $PSScriptRoot 'dsp-worklet.js'))),
    (Script (& $read (Join-Path $PSScriptRoot 'web-host.js')))
) -join "`n"

# Inline every <script src="js/..."></script> in order
$html = [regex]::Replace($html, '<script src="js/([\w.-]+)"></script>', {
    param($m)
    $name = $m.Groups[1].Value
    $code = Script (& $read (Join-Path $ui "js\$name"))
    if ($name -eq 'engine-juce.js') { return "$hostScripts`n$code" }
    return $code
})
if ($html -match 'src="js/') { throw 'a script was not inlined' }

$banner = @"
<!--
  No Strings v${version}: web build. ONE self-contained file: UI, DSP and factory presets.
  GENERATED by vst/webhost/build-web.ps1 from vst/ui + vst/webhost: edit those, not this file.
  Open in Chrome or Edge (works straight from disk; start.bat serves it for the lower-latency AudioWorklet path).
-->
"@
$html = $html.Replace('<!doctype html>', "<!doctype html>`n$banner")
$html = $html.Replace('<title>No Strings</title>', "<title>No Strings v$version</title>")

foreach ($out in @((Join-Path $repo 'web\index.html'), (Join-Path $repo 'docs\index.html'))) {
    New-Item -ItemType Directory -Force (Split-Path $out) | Out-Null
    [IO.File]::WriteAllText($out, $html, $utf8)
    Write-Host ("Wrote {0} ({1:N0} KB)" -f $out, ((Get-Item $out).Length / 1KB))
}
