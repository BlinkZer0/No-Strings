// ============================================================================
//  NoStringsGenParams: writes ui/js/params.js from the C++ parameter table
//  (core/ParamTable.h) plus the body / excitation / material facts the UI
//  needs, so the UI can never drift from the plugin.
//
//    NoStringsGenParams <output path>
// ============================================================================
#include <cstdio>
#include <string>
#include "ParamTable.h"

using namespace nostrings;

static std::string js (const std::string& s)
{
    std::string o = "'";
    for (char c : s) { if (c == '\'' || c == '\\') o += '\\'; o += c; }
    return o + "'";
}

static std::string num (float v)
{
    char buf[32];
    std::snprintf (buf, sizeof buf, "%g", (double) v);
    return buf;
}

int main (int argc, char** argv)
{
    if (argc < 2) { std::fprintf (stderr, "usage: NoStringsGenParams <ui/js/params.js>\n"); return 1; }
    std::string out;
    out += "// ============================================================================\n"
           "//  GENERATED by NoStringsGenParams from vst/core/ParamTable.h. Do not edit:\n"
           "//  run vst\\build.bat (or the NoStringsGenParams target) to regenerate.\n"
           "// ============================================================================\n"
           "'use strict';\n\n"
           "const PARAM_DEFS = [\n";
    for (const auto& p : paramTable())
    {
        out += "  { id: " + js (p.id) + ", name: " + js (p.name) + ", group: " + js (p.group);
        if (p.kind == ParamKind::Choice)
        {
            out += ", type: 'choice', min: 0, max: " + num (p.max) + ", step: 1, def: " + num (p.def) + ", choices: [";
            for (size_t i = 0; i < p.choices.size(); ++i) out += (i ? ", " : "") + js (p.choices[i]);
            out += "]";
        }
        else
        {
            if (p.kind == ParamKind::Int) out += ", type: 'int', step: 1";
            out += ", min: " + num (p.min) + ", max: " + num (p.max) + ", def: " + num (p.def);
            if (! p.unit.empty()) out += ", unit: " + js (p.unit);
            if (p.logSkew) out += ", skew: 'log'";
        }
        if (p.noPreset) out += ", noPreset: true";
        out += " },\n";
    }
    out += "];\n\n";

    out += "// the bodies: strings (MIDI notes), natural range, frets, electric, shape for the picture\n"
           "const BODIES = [\n";
    static const char* shapes[kNumBodies] = { "cello", "cello", "cello", "cello", "cello", "guitar", "slab", "frame" };
    for (int b = 0; b < kNumBodies; ++b)
    {
        const auto& bp = bodyProfile (b);
        out += "  { name: " + js (bp.name) + ", strings: [";
        for (int k = 0; k < bp.numStrings; ++k) out += (k ? ", " : "") + std::to_string (bp.strings[k]);
        out += "], rangeLo: " + std::to_string (bp.rangeLo) + ", rangeHi: " + std::to_string (bp.rangeHi)
             + ", fretted: " + (bp.fretted ? "true" : "false") + ", electric: " + (bp.electric ? "true" : "false")
             + ", shape: " + js (shapes[b]) + " },\n";
    }
    out += "];\n\n";

    // the full body and material tables for the JS engine (dsp-worklet.js), so the data can never drift
    out += "// full body profiles for the JS engine (mirror of core/body/BodyProfiles.h)\n"
           "const BODY_PROFILES = [\n";
    for (int b = 0; b < kNumBodies; ++b)
    {
        const auto& bp = bodyProfile (b);
        out += "  { name: " + js (bp.name) + ", strings: [";
        for (int k = 0; k < bp.numStrings; ++k) out += (k ? ", " : "") + std::to_string (bp.strings[k]);
        out += "], rangeLo: " + std::to_string (bp.rangeLo) + ", rangeHi: " + std::to_string (bp.rangeHi)
             + ", fretted: " + (bp.fretted ? "true" : "false") + ", electric: " + (bp.electric ? "true" : "false")
             + ",\n    hillHz: " + num ((float) bp.hillHz) + ", hillDb: " + num ((float) bp.hillDb) + ", hillQ: " + num ((float) bp.hillQ)
             + ", bridgeLpHz: " + num ((float) bp.bridgeLpHz) + ",\n    low: [";
        for (int k = 0; k < 6; ++k)
            out += std::string (k ? ", " : "") + "[" + num ((float) bp.low[k].hz) + ", " + num ((float) bp.low[k].q) + ", " + num ((float) bp.low[k].gain) + "]";
        out += "],\n    cloudCount: " + std::to_string (bp.cloudCount) + ", cloudLoHz: " + num ((float) bp.cloudLoHz) + ", cloudHiHz: " + num ((float) bp.cloudHiHz)
             + ", cloudQLo: " + num ((float) bp.cloudQLo) + ", cloudQHi: " + num ((float) bp.cloudQHi) + ",\n    env: [";
        for (int k = 0; k < 7; ++k)
            out += std::string (k ? ", " : "") + "[" + num ((float) bp.env[k].hz) + ", " + num ((float) bp.env[k].db) + "]";
        out += "],\n    direct: " + num ((float) bp.direct) + ", coupling: [";
        for (int k = 0; k < 2; ++k)
            out += std::string (k ? ", " : "") + "[" + num ((float) bp.coupling[k].hz) + ", " + num ((float) bp.coupling[k].q) + ", " + num ((float) bp.coupling[k].gain) + "]";
        out += "],\n    spread: " + num ((float) bp.spread) + ", airLpHz: " + num ((float) bp.airLpHz) + ", proximityDb: " + num ((float) bp.proximityDb)
             + ", stoppedDecay: " + num ((float) bp.stoppedDecay) + ", stoppedHf: " + num ((float) bp.stoppedHf) + ", outputDb: " + num ((float) bp.outputDb) + " },\n";
    }
    out += "];\n\n// material profiles for the JS engine (mirror of core/Materials.h)\nconst MATERIAL_PROFILES = [\n";
    for (int m = 0; m < kNumMaterials; ++m)
    {
        const auto& mp = materialProfile (m);
        out += "  { name: " + js (mp.name) + ", decay: " + num ((float) mp.decay) + ", hfRatio: " + num ((float) mp.hfRatio)
             + ", stiffness: " + num ((float) mp.stiffness) + ", muS: " + num ((float) mp.muS) + ", muD: " + num ((float) mp.muD)
             + ", v0: " + num ((float) mp.v0) + ", rho: " + num ((float) mp.rho) + ", glide: " + num ((float) mp.glide) + " },\n";
    }
    out += "];\n\n";

    out += "const EXCITATIONS = [";
    for (int e = 0; e < kNumExcitations; ++e) out += (e ? ", " : "") + js (excitationName (e));
    out += "];\nconst BOWED_EXCITATIONS = [";
    bool first = true;
    for (int e = 0; e < kNumExcitations; ++e) if (isBowed (e)) { out += (first ? "" : ", ") + std::to_string (e); first = false; }
    out += "];\nconst EXC_ARCO = " + std::to_string (excArco) + ", EXC_HARMONIC = " + std::to_string (excHarmonic)
         + ", EXC_MALLET = " + std::to_string (excMallet) + ", EXC_EBOW = " + std::to_string (excEBow)
         + ", EXC_SPICCATO = " + std::to_string (excSpiccato) + ";\n";
    out += "const SYMP_CUSTOM = " + std::to_string (sympCustom) + ", SYMP_SCALE = " + std::to_string (sympScale)
         + ", MAX_SYMPATHETIC = " + std::to_string (kMaxSympathetic) + ";\n";
    out += "const NUM_VOICES = " + std::to_string (kNumVoices) + ";\n";

    // sympathetic tunings per mode, so the UI can show which notes the bank is tuned to
    out += "\n// scale degrees (semitones from the key) per scale, for the sympathetic tuning readout\n"
           "const SCALE_DEGREES = [[0,2,4,5,7,9,11],[0,2,3,5,7,8,10],[0,2,3,5,7,9,10],[0,2,4,5,7,9,10],[0,2,4,7,9],[0,2,3,5,7,8,11],[0,7]];\n";

    out += R"JS(
const PARAM_BY_ID = Object.fromEntries(PARAM_DEFS.map(d => [d.id, d]));

function clamp(v, lo, hi) { return v < lo ? lo : v > hi ? hi : v; }

function defaultParamValues() {
  return Object.fromEntries(PARAM_DEFS.map(d => [d.id, d.def]));
}

// value <-> 0..1 normalized (same mapping the VST host will see)
function paramToNorm(d, v) {
  if (d.skew === 'log') return clamp(Math.log(v / d.min) / Math.log(d.max / d.min), 0, 1);
  return clamp((v - d.min) / (d.max - d.min), 0, 1);
}

function paramFromNorm(d, n) {
  n = clamp(n, 0, 1);
  let v = d.skew === 'log' ? d.min * Math.pow(d.max / d.min, n) : d.min + n * (d.max - d.min);
  if (d.step) v = Math.round(v / d.step) * d.step;
  return clamp(v, d.min, d.max);
}

const NOTE_NAMES_FMT = ['C', 'C#', 'D', 'D#', 'E', 'F', 'F#', 'G', 'G#', 'A', 'A#', 'B'];
function noteNameOf(n) { return NOTE_NAMES_FMT[((n % 12) + 12) % 12] + (Math.floor(n / 12) - 1); }

function formatParam(d, v) {
  if (d.type === 'choice') return d.choices[clamp(Math.round(v), 0, d.choices.length - 1)];
  switch (d.unit) {
    case 's':    return v < 1 ? `${Math.round(v * 1000)} ms` : `${v.toFixed(2)} s`;
    case 'Hz':   return `${v.toFixed(1)} Hz`;
    case 'st':   return `${Math.round(v)} st`;
    case 'ct':   return `${Math.round(v)} ct`;
    case '%':    return `${Math.round(v * 100)}%`;
    case 'dB':   return `${v > 0.05 ? '+' : ''}${v.toFixed(1)} dB`;
    case 'note': return noteNameOf(Math.round(v));
    default:     return d.type === 'int' ? String(Math.round(v)) : String(v);
  }
}

// MIDI notes the sympathetic bank is tuned to, for the readout (mirrors Sympathetic.h)
function sympatheticNotes(values) {
  const count = Math.round(values.sympCount), mode = Math.round(values.sympMode);
  const body = BODIES[Math.round(values.body)];
  const deg = SCALE_DEGREES[Math.round(values.sympScale)] || SCALE_DEGREES[0];
  const out = [];
  for (let i = 0; i < count; i++) {
    let n;
    if (mode === SYMP_SCALE) n = 48 + Math.round(values.sympKey) + deg[i % deg.length] + 12 * Math.floor(i / deg.length);
    else if (mode === SYMP_CUSTOM) n = Math.round(values[`sympNote${i + 1}`]);
    else n = body.strings[i % body.strings.length] + 12 * Math.floor(i / body.strings.length);
    out.push(clamp(n, 24, 108));
  }
  return out;
}
)JS";

    FILE* f = std::fopen (argv[1], "wb");
    if (f == nullptr) { std::fprintf (stderr, "cannot write %s\n", argv[1]); return 1; }
    std::fwrite (out.data(), 1, out.size(), f);
    std::fclose (f);
    std::printf ("wrote %s (%d parameters)\n", argv[1], (int) paramTable().size());
    return 0;
}
